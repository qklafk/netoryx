def test_truncate_rules() -> None:
    assert truncate("short", 30) == "short"
    assert truncate("  padded  ", 6) == "padded"
    assert truncate("abcdefgh", 5) == "abcd…"
    assert truncate("abc defgh", 5) == "abc…"
    assert truncate("abcdef", 1) == "…"
    assert truncate("abcdef", 0) == ""
    # Never split a flag (2 code points) or a ZWJ family emoji.
    assert truncate("🇩🇪🇳🇱🇫🇷", 4) == "🇩🇪…"
    assert truncate("ab👨‍👩‍👧xyz", 5) == "ab…"


def test_graphemes() -> None:
    assert list(graphemes("🇩🇪🇳🇱")) == ["🇩🇪", "🇳🇱"]
    assert list(graphemes("é")) == ["é"]
    assert list(graphemes("👍🏽!")) == ["👍🏽", "!"]
    assert list(graphemes("❤️a")) == ["❤️", "a"]
    assert list(graphemes("🏴󠁧󠁢󠁳󠁣󠁴󠁿x")) == ["🏴󠁧󠁢󠁳󠁣󠁴󠁿", "x"]
    assert list(graphemes("")) == []
