def test_xhttp_cdn_extra_dict_is_sorted_like_go_but_equivalent() -> None:
    """3x-ui marshals the extra map with sorted keys (Go json.Marshal); the doc example is hand-ordered."""
    params = {**CDN_PARAMS, "extra": json.loads(CDN_EXTRA_DOC)}
    link = build_vless(UUID, "cdn.example.ru", 443, params, "DE LTE CDN")
    extra = query_of(link)["extra"]
    assert json.loads(extra) == json.loads(CDN_EXTRA_DOC)
    assert list(json.loads(extra)) == sorted(json.loads(CDN_EXTRA_DOC))
    assert query_of(link) | {"extra": ""} == query_of(CDN_GOLDEN) | {"extra": ""}


