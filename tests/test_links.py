def test_remark_is_uri_component_encoded_and_emoji_safe() -> None:
    link = build_vless(UUID, "1.2.3.4", 443, {"type": "tcp"}, "🇩🇪 Германия · LTE")
    fragment = link.split("#", 1)[1]
    assert " " not in fragment and "+" not in fragment
    assert unquote(fragment) == "🇩🇪 Германия · LTE"


def test_server_description_appended_as_literal_base64() -> None:
    link = build_vless(UUID, "1.2.3.4", 443, {"type": "tcp"}, "DE", "Быстрый сервер")
    fragment = link.split("#", 1)[1]
    remark, description = fragment.split("?serverDescription=")
    assert remark == "DE"
    assert base64.b64decode(description).decode() == "Быстрый сервер"


def test_empty_remark_has_no_fragment_and_empty_description_ignored() -> None:
    assert "#" not in build_vless(UUID, "1.2.3.4", 443, {"type": "tcp"}, "", "")


