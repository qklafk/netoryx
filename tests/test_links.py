def query_of(link: str) -> dict[str, str]:
    return dict(parse_qsl(urlsplit(link).query, keep_blank_values=True))


def endpoint(
    *,
    kind: EndpointKind = EndpointKind.DIRECT,
    profile: EndpointProfile = EndpointProfile.STANDARD,
    address: str = "203.0.113.10",
    port: int | None = None,
    overrides: dict[str, Any] | str | None = None,
    remark: str | None = None,
) -> Endpoint:
    raw = json.dumps(overrides) if isinstance(overrides, dict) else overrides
    return Endpoint(
        id=1, inbound_id=1, kind=kind, profile=profile, address=address, port=port, overrides=raw, remark=remark
    )


