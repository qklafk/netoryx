def test_foreign_security_keys_dropped() -> None:
    params = {**REALITY, "type": "tcp", "security": "tls", "spx": "/x", "pqv": "q", "alpn": "h2"}
    query = query_of(build_vless(UUID, "1.2.3.4", 443, params, "x"))
    assert not {"pbk", "sid", "spx", "pqv", "support-x25519mlkem768"} & set(query)
    assert query["alpn"] == "h2" and query["sni"] == "www.example.ru"

    none_query = query_of(build_vless(UUID, "1.2.3.4", 443, {**params, "security": "none"}, "x"))
    assert not {"sni", "fp", "alpn", "pbk"} & set(none_query)

    reality_query = query_of(build_vless(UUID, "1.2.3.4", 443, {**REALITY, "type": "tcp", "alpn": "h2"}, "x"))
    assert "alpn" not in reality_query


