const PATTERNS = new Map<string, [RegExp, string][]>();

function patterns(lang: string, dict: Record<string, string>): [RegExp, string][] {
  let list = PATTERNS.get(lang);
  if (!list) {
    list = Object.keys(dict)
      .filter(key => /\{\d\}/.test(key))
      .sort((a, b) => b.length - a.length)
      .map(key => {
        const source = key.split(/\{\d\}/).map(part => part.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('(.+?)');
        const order = [...key.matchAll(/\{(\d)\}/g)].map(match => match[1]);
        let out = dict[key];
        order.forEach((name, position) => { out = out.replace(`{${name}}`, `\u0000${position}\u0000`); });
        return [new RegExp(`^${source}$`), out] as [RegExp, string];
      });
    PATTERNS.set(lang, list);
  }
  return list;
}

/** Text in `lang`: the inline Russian or English, a dictionary entry, or the closest fallback. */
export function translate(lang: string, ru: string, en: string): string {
  if (lang === 'ru') return ru;
  if (lang === 'en') return en;
  const dict = DICTIONARIES[lang];
  if (dict) {
    const exact = dict[en];
    if (exact !== undefined) return exact;
    for (const [pattern, out] of patterns(lang, dict)) {
      const match = pattern.exec(en);
      if (match) return out.replace(/\u0000(\d)\u0000/g, (_, position: string) => match[Number(position) + 1] ?? '');
    }
  }
  return FALLBACK[lang] === 'ru' ? ru : en;
}

/** Supported language of a browser / Telegram language tag (`zh-Hans` -> `zh`), else `fallback`. */
export function detectLanguage(tag: string | undefined | null, fallback = 'ru'): string {
  const primary = (tag || '').toLowerCase().replace('_', '-').split('-')[0];
  const code = primary === 'ua' ? 'uk' : primary;
  return code in LANGUAGE_NAMES ? code : fallback;
}
